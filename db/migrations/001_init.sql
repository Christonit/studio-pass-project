-- =============================================================================
-- StudioPass — migration 001: initial schema
-- Plain PostgreSQL (14+). Works on Supabase and Railway.
--
-- Run once on an empty database:
--   Supabase: SQL Editor → paste this file → Run
--   Railway:  psql "$DATABASE_URL" -f db/migrations/001_init.sql
-- Then (optional) load the demo data:  db/seed.sql
-- Undo everything:                     db/migrations/001_init_down.sql
--
-- Design notes
-- - Users are keyed by EMAIL (primary key). Everything a user owns points to
--   users(email): bookings, credit transactions, proposals, classes taught,
--   and created_by / reviewed_by for admin actions.
-- - Passwords are stored as PLAIN TEXT on purpose (student prototype).
-- - Other tables use integer ids. They are "generated by default" so the seed
--   can insert fixed ids; db/seed.sql resets the sequences afterwards.
-- - Row level security is switched on with NO policies. On Supabase that
--   blocks the public REST API (anon key) from reading plain-text passwords;
--   the app connects with the database connection string, whose owner role
--   bypasses RLS. On Railway it changes nothing.
-- =============================================================================

begin;

-- --- Users -------------------------------------------------------------------
create table users (
  email       text primary key,
  password    text not null,
  role        text not null,
  name        text not null,
  zip         text,
  credits     integer,
  zip_tags    text[] not null default '{}',
  bio         text not null default '',
  demo        boolean not null default false,
  created_at  timestamptz not null default now(),

  constraint users_email_lowercase check (email = lower(email)),
  constraint users_email_format    check (email ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$'),
  constraint users_password_length check (char_length(password) between 4 and 100),
  constraint users_role            check (role in ('member', 'instructor', 'admin')),
  constraint users_zip             check (zip is null or zip ~ '^\d{5}$'),
  constraint users_zip_tags        check (array_to_string(zip_tags, ',') ~ '^(\d{5}(,\d{5})*)?$'),
  -- Members always have a balance that can't go negative; others have none.
  constraint users_credits check (
    (role = 'member' and credits is not null and credits >= 0) or (role <> 'member' and credits is null)
  )
);

-- --- Locations (studios) -----------------------------------------------------
create table locations (
  id            bigint generated by default as identity primary key,
  name          text not null,
  neighborhood  text not null default '',
  address       text not null default '',
  zip           text not null check (zip ~ '^\d{5}$'),
  zip_tags      text[] not null default '{}' check (array_to_string(zip_tags, ',') ~ '^(\d{5}(,\d{5})*)?$'),
  created_by    text references users(email) on update cascade,
  created_at    timestamptz not null default now()
);

-- --- Credit packages ---------------------------------------------------------
create table credit_packages (
  id         bigint generated by default as identity primary key,
  name       text not null,
  credits    integer not null check (credits > 0),
  price_usd  numeric(8, 2) not null check (price_usd >= 0),
  active     boolean not null default true
);

-- --- Proposals (instructor → admin) ------------------------------------------
create table proposals (
  id                bigint generated by default as identity primary key,
  instructor_email  text not null references users(email) on update cascade,
  title             text not null check (char_length(title) between 3 and 80),
  discipline        text not null check (discipline in ('Yoga', 'Pilates', 'HIIT', 'Spin', 'Barre', 'Boxing', 'Strength', 'Dance')),
  level             text not null check (level in ('Beginner', 'Intermediate', 'Advanced')),
  description       text not null default '',
  location_id       bigint not null references locations(id),
  duration_min      integer not null check (duration_min between 15 and 180),
  capacity          integer not null check (capacity between 1 and 60),
  credit_cost       integer not null check (credit_cost between 1 and 20),
  first_session_at  timestamptz not null,
  weekly_repeats    integer not null default 1 check (weekly_repeats between 1 and 12),
  status            text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  admin_note        text,
  reviewed_by       text references users(email) on update cascade,
  reviewed_at       timestamptz,
  class_id          bigint, -- foreign key added below, after classes exists
  created_at        timestamptz not null default now()
);

-- --- Classes -----------------------------------------------------------------
create table classes (
  id                bigint generated by default as identity primary key,
  title             text not null check (char_length(title) between 3 and 80),
  discipline        text not null check (discipline in ('Yoga', 'Pilates', 'HIIT', 'Spin', 'Barre', 'Boxing', 'Strength', 'Dance')),
  level             text not null check (level in ('Beginner', 'Intermediate', 'Advanced')),
  description       text not null default '',
  instructor_email  text not null references users(email) on update cascade,
  location_id       bigint not null references locations(id),
  duration_min      integer not null check (duration_min between 15 and 180),
  capacity          integer not null check (capacity between 1 and 60), -- default for new sessions
  credit_cost       integer not null check (credit_cost between 1 and 20), -- base price
  status            text not null default 'active' check (status in ('active', 'archived')),
  proposal_id       bigint references proposals(id),
  created_by        text references users(email) on update cascade,
  created_at        timestamptz not null default now()
);

alter table proposals
  add constraint proposals_class_id_fkey foreign key (class_id) references classes(id);

-- --- Sessions (one scheduled occurrence of a class) --------------------------
create table sessions (
  id               bigint generated by default as identity primary key,
  class_id         bigint not null references classes(id),
  starts_at        timestamptz not null,
  capacity         integer not null check (capacity between 1 and 60),
  credit_override  integer check (credit_override between 0 and 20), -- null = use the class price
  status           text not null default 'scheduled' check (status in ('scheduled', 'cancelled')),
  cancel_reason    text,
  created_at       timestamptz not null default now()
);

-- --- Bookings ----------------------------------------------------------------
create table bookings (
  id                bigint generated by default as identity primary key,
  session_id        bigint not null references sessions(id),
  member_email      text not null references users(email) on update cascade,
  status            text not null default 'booked' check (status in ('booked', 'cancelled', 'attended', 'no_show')),
  credits_spent     integer not null check (credits_spent >= 0),
  refunded_credits  integer not null default 0 check (refunded_credits between 0 and credits_spent),
  created_at        timestamptz not null default now(),
  cancelled_at      timestamptz,
  constraint bookings_cancelled_at check ((status = 'cancelled') = (cancelled_at is not null))
);

-- --- Credit ledger -----------------------------------------------------------
-- users.credits must always equal the sum of a member's deltas.
create table credit_transactions (
  id            bigint generated by default as identity primary key,
  member_email  text not null references users(email) on update cascade,
  delta         integer not null, -- can be 0 for a free (override = 0) booking
  type          text not null check (type in ('purchase', 'booking', 'refund', 'adjustment')),
  package_id    bigint references credit_packages(id),
  booking_id    bigint references bookings(id),
  amount_usd    numeric(8, 2),
  note          text not null default '',
  created_at    timestamptz not null default now()
);

-- --- Indexes -----------------------------------------------------------------
-- A member can hold only one active booking per session.
create unique index bookings_one_active_per_member on bookings (session_id, member_email) where status <> 'cancelled';
create index bookings_member_idx            on bookings (member_email);
create index bookings_session_idx           on bookings (session_id);
create index sessions_starts_at_idx         on sessions (starts_at);
create index sessions_class_idx             on sessions (class_id, starts_at);
create index classes_instructor_idx         on classes (instructor_email);
create index classes_location_idx           on classes (location_id);
create index proposals_instructor_idx       on proposals (instructor_email, created_at desc);
create index proposals_status_idx           on proposals (status);
create index credit_transactions_member_idx on credit_transactions (member_email, created_at desc);
create index locations_zip_tags_idx         on locations using gin (zip_tags);

-- --- Row level security (see note at the top) ---------------------------------
alter table users               enable row level security;
alter table locations           enable row level security;
alter table credit_packages     enable row level security;
alter table proposals           enable row level security;
alter table classes             enable row level security;
alter table sessions            enable row level security;
alter table bookings            enable row level security;
alter table credit_transactions enable row level security;

commit;
