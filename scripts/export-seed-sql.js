// npm run db:seed-sql — writes db/seed.sql from the same dummy data the app uses
// (lib/server/db/seed.js), so Postgres and the local JSON store start identical.
// Dates are relative to when you run this, so re-run it before a demo.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSeed } from '../lib/server/db/seed.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'db', 'seed.sql');

// Columns per table, in insert order (parents before children).
const TABLES = [
  ['users', ['email', 'password', 'role', 'name', 'zip', 'credits', 'zip_tags', 'bio', 'demo', 'created_at']],
  ['locations', ['id', 'name', 'neighborhood', 'address', 'zip', 'zip_tags', 'created_by', 'created_at']],
  ['credit_packages', ['id', 'name', 'credits', 'price_usd', 'active']],
  // class_id is filled in after classes exist (the two tables point at each other).
  ['proposals', ['id', 'instructor_email', 'title', 'discipline', 'level', 'description', 'location_id', 'duration_min', 'capacity', 'credit_cost', 'first_session_at', 'weekly_repeats', 'status', 'admin_note', 'reviewed_by', 'reviewed_at', 'created_at']],
  ['classes', ['id', 'title', 'discipline', 'level', 'description', 'instructor_email', 'location_id', 'duration_min', 'capacity', 'credit_cost', 'status', 'proposal_id', 'created_by', 'created_at']],
  ['sessions', ['id', 'class_id', 'starts_at', 'capacity', 'credit_override', 'status', 'cancel_reason', 'created_at']],
  ['bookings', ['id', 'session_id', 'member_email', 'status', 'credits_spent', 'refunded_credits', 'created_at', 'cancelled_at']],
  ['credit_transactions', ['id', 'member_email', 'delta', 'type', 'package_id', 'booking_id', 'amount_usd', 'note', 'created_at']],
];

const quote = (s) => `'${String(s).replaceAll("'", "''")}'`;
function literal(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value)) return value.length ? `array[${value.map(quote).join(', ')}]::text[]` : `'{}'::text[]`;
  return quote(value);
}

function insert(table, columns, rows, chunk = 100) {
  const out = [];
  for (let i = 0; i < rows.length; i += chunk) {
    const values = rows.slice(i, i + chunk).map((r) => `  (${columns.map((c) => literal(r[c])).join(', ')})`);
    out.push(`insert into ${table} (${columns.join(', ')}) values\n${values.join(',\n')};`);
  }
  return out.join('\n\n');
}

const db = buildSeed();
const parts = [
  `-- StudioPass demo data. GENERATED by scripts/export-seed-sql.js on ${db.meta.seeded_at}.`,
  '-- Run after db/migrations/001_init.sql, on empty tables. Re-generate with: npm run db:seed-sql',
  `-- Every demo account's password is "studiopass" (plain text, prototype only).`,
  '',
  'begin;',
  '',
];
for (const [table, columns] of TABLES) {
  parts.push(`-- ${table} (${db[table].length} rows)`, insert(table, columns, db[table]), '');
}
const links = db.proposals.filter((p) => p.class_id);
if (links.length) {
  parts.push('-- proposals that became classes');
  for (const p of links) parts.push(`update proposals set class_id = ${p.class_id} where id = ${p.id};`);
  parts.push('');
}
parts.push("-- Move each id sequence past the inserted ids so new rows don't collide.");
for (const [table] of TABLES.slice(1)) {
  parts.push(`select setval(pg_get_serial_sequence('${table}', 'id'), coalesce((select max(id) from ${table}), 0) + 1, false);`);
}
parts.push('', 'commit;', '');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, parts.join('\n'));
const counts = TABLES.map(([t]) => `${db[t].length} ${t}`).join(', ');
console.log(`Wrote ${path.relative(root, OUT)}: ${counts}`);
